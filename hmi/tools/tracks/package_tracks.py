#!/usr/bin/env python3
"""Stage 4 of the track data: split it into what the Track app loads.

    package_tracks.py BUILD_DIR OUT_DIR

BUILD_DIR is what build_tracks.py (and label_tracks.py) wrote. OUT_DIR gets

  index.json        one short entry per track, for listing, searching, filtering
                    and sorting a thousand tracks without loading any drawings:
                    id, name, place, state, country, type, length_m, center
  tracks/<id>.json  the rest, loaded when a track is opened: outline, loop,
                    pit, start/finish gate or drag strip starts, geofence
  svg/<id>-light.svg, svg/<id>-dark.svg
  README.md         what the fields mean, and the licence

Arriving at a track does not need the index searched: test the car's position
against each entry's center first (a few km), then that track's geofence.
"""
import json
import os
import shutil
import sys

INDEX_FIELDS = ("id", "name", "place", "state", "country", "type", "length_m", "center")

README = """# Track data

Generated by `hmi/tools/tracks/` from OpenStreetMap. Do not edit by hand:
change the tools and regenerate.

Map data (c) OpenStreetMap contributors, available under the Open Database
License (ODbL) 1.0: https://opendatacommons.org/licenses/odbl/. The outlines
are OpenStreetMap's raceways; anyone who redistributes this data must keep
this attribution and share any changes to it under the same licence.

## Files

- `index.json`: every track, briefly: `id`, `name`, `place`, `state`,
  `country`, `type` (`road`, `oval` or `drag`), `length_m`, `center` [lat, lon].
- `tracks/<id>.json`: one track in full. All coordinates are [lat, lon].
  - `outline`: every raceway at the track, as lines, for drawing.
  - `pit`: pit lanes, as lines.
  - `loop` (road, oval): the main circuit as one closed ring.
  - `gate` (road, oval): the start/finish line. `ends` are its two ends,
    across the track, about 28 m apart. `heading` is the direction of travel
    across it in degrees, trusted only when `direction_known`. `placed` says
    how it was found: `pit_lane` (on the straight beside the pits) or
    `longest_straight`. It is an estimate, not a survey: laps are timed from
    one crossing to the next, so lap times are right wherever it sits, but
    offer to move it ("Set start/finish here") for official-style timing.
  - `drag` (drag strips): `starts`, a candidate start gate at each end of the
    strip, and `distance_m` to the finish (402.3 m for a quarter mile, 201.2 m
    for an eighth). OpenStreetMap does not say which end is the start; take it
    from the direction of the first run.
  - `geofence`: a closed ring around the venue, 250 m beyond it. Inside it,
    the car is at the track.
  - `osm`: the OpenStreetMap venue and ways it came from.
- `svg/<id>-light.svg`, `svg/<id>-dark.svg`: the outline in the HMI's light and
  dark colours, north up, on a transparent background; the start/finish line
  in the accent colour.
"""


def main(src, out):
    data = json.load(open(os.path.join(src, "tracks.json")))
    if os.path.exists(out):
        shutil.rmtree(out)
    os.makedirs(os.path.join(out, "tracks"))
    shutil.copytree(os.path.join(src, "svg"), os.path.join(out, "svg"))
    index = []
    for t in data["tracks"]:
        index.append({k: t.get(k) for k in INDEX_FIELDS})
        with open(os.path.join(out, "tracks", f"{t['id']}.json"), "w") as f:
            json.dump(t, f, separators=(",", ":"))
    with open(os.path.join(out, "index.json"), "w") as f:
        json.dump({"attribution": data["attribution"], "count": len(index), "tracks": index},
                  f, separators=(",", ":"), ensure_ascii=False)
    with open(os.path.join(out, "README.md"), "w") as f:
        f.write(README)
    print(f"{len(index)} tracks, index {os.path.getsize(os.path.join(out, 'index.json')) // 1024} KB")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
